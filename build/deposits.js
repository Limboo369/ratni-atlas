(async () => {
  const maps = { evropa: await RA.loadMap(), svijet: await RA.loadMap(JSON.parse(fs.readFileSync(R + 'build/svijet/map.json', 'utf8'))) };
  const out = {};
  for (const [id, m] of Object.entries(maps)) {
    out[id] = {};
    const W = m.W, H = m.H;
    for (const [k, list] of Object.entries(PLACES)) {
      const cells = [];
      for (const [lat, lon] of list) {
        const x = RA.lonToX(lon), y = RA.latToY(lat);
        if (x < m.X0 || x >= m.X1 || y < m.Y0 || y >= m.Y1) continue;
        const c0 = m.cellAt(x, y), cx = c0 % W, cy = (c0 / W) | 0;
        let best = -1, bd = 1e9;
        for (let dy = -4; dy <= 4; dy++)
          for (let dx = -4; dx <= 4; dx++) {
            const xx = cx + dx, yy = cy + dy;
            if (xx < 0 || yy < 0 || xx >= W || yy >= H || !m.land[yy * W + xx]) continue;
            const d = dx * dx + dy * dy;
            if (d < bd) {
              bd = d;
              best = yy * W + xx;
            }
          }
        if (best >= 0 && !cells.includes(best)) cells.push(best);
      }
      out[id][k] = cells.sort((a, b) => a - b);
    }
    console.log(id, Object.entries(out[id]).map(([k, v]) => `${k} ${v.length}`).join(', '));
  }
  const js = `'use strict';
/* Resource deposits in grid cells per map — generated by build/deposits.js (edit the places there, then run it). */
RA.DEPOSITS = ${JSON.stringify(out)};
`;
  fs.writeFileSync(R + 'src/01b-deposits.js', js);
})();
